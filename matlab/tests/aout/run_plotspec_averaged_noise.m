%% Regression checks for median noise-floor statistics after averaging

fprintf('[%s] median noise floor after power and coherent averaging\n', mfilename);

rngState = rng;
rng(20261103);
N = 32768;
n = 0:N-1;
toneBin = 379;

%% White noise: the median method must agree with direct integration.
% Rectangular-window bins of white noise are independent. When each of the
% N/2 bins averages K exponential powers (K = M for power averaging, K = 1
% for coherent averaging), the sampling std of median/direct is below
% 1.04/sqrt(K*N/2).
cases = { ...
    'normal', 1; ...
    'normal', 4; ...
    'coherent', 4; ...
    'coherent', 16 ...
};

for ii = 1:size(cases, 1)
    averageMode = cases{ii, 1};
    M = cases{ii, 2};
    sig = 0.7 * sin(2*pi*toneBin*n/N + 2*pi*rand(M, 1)) + 2e-3 * randn(M, N);

    [~, ~, ~, snrMedian] = plotspec( ...
        sig, 1, 2, 5, ...
        'window', 'rect', ...
        'sideBin', 0, ...
        'NFMethod', 'median', ...
        'averageMode', averageMode, ...
        'disp', false, ...
        'label', false);
    [~, ~, ~, snrDirect] = plotspec( ...
        sig, 1, 2, 5, ...
        'window', 'rect', ...
        'sideBin', 0, ...
        'NFMethod', 'exclude', ...
        'averageMode', averageMode, ...
        'disp', false, ...
        'label', false);

    if strcmp(averageMode, 'coherent')
        nExponentials = 1;
    else
        nExponentials = M;
    end
    toleranceDb = 10*log10(1 + 4*1.04/sqrt(nExponentials*N/2));
    assert(abs(snrMedian - snrDirect) < toleranceDb, ...
        'Median noise disagrees with direct integration (%s, M=%d): %.4f dB', ...
        averageMode, M, snrMedian - snrDirect);
end

%% Appended empty records must not change coherent-averaging results.
capture = 0.7 * sin(2*pi*toneBin*n/N + 0.3) + 2e-3 * randn(1, N);
padded = [capture; zeros(7, N)];
nfMethods = {'auto', 'median', 'mean', 'exclude'};

for ii = 1:numel(nfMethods)
    [enob, sndr, sfdr, snr, thd, sigpwr, noi, nsd] = plotspec( ...
        capture, 1, 2, 5, ...
        'window', 'rect', ...
        'sideBin', 0, ...
        'NFMethod', nfMethods{ii}, ...
        'averageMode', 'coherent', ...
        'disp', false, ...
        'label', false);
    [enobPad, sndrPad, sfdrPad, snrPad, thdPad, sigpwrPad, noiPad, nsdPad] = plotspec( ...
        padded, 1, 2, 5, ...
        'window', 'rect', ...
        'sideBin', 0, ...
        'NFMethod', nfMethods{ii}, ...
        'averageMode', 'coherent', ...
        'disp', false, ...
        'label', false);

    reference = [enob, sndr, sfdr, snr, thd, sigpwr, noi, nsd];
    withEmpty = [enobPad, sndrPad, sfdrPad, snrPad, thdPad, sigpwrPad, noiPad, nsdPad];
    assert(max(abs(withEmpty - reference)) < 1e-9, ...
        'Empty records changed coherent-averaging metrics (NFMethod=%s).', ...
        nfMethods{ii});
end

%% Plot titles must use the records that actually entered the average.
fig = figure('Visible', 'off');
cleanupFigure = onCleanup(@() close(fig));
for averageMode = {'normal', 'coherent'}
    for nValid = [1, 3]
        clf(fig);
        plotspec([repmat(capture, nValid, 1); zeros(7, N)], 1, 2, 5, ...
            'window', 'rect', 'sideBin', 0, ...
            'averageMode', averageMode{1}, 'disp', true, 'label', false);
        titleText = get(get(gca, 'Title'), 'String');
        if nValid == 1
            assert(strcmp(titleText, 'Power Spectrum'));
        elseif strcmp(averageMode{1}, 'coherent')
            assert(strcmp(titleText, 'Power Spectrum (3x Coherently Averaged)'));
        else
            assert(strcmp(titleText, 'Power Spectrum (3x Averaged)'));
        end
    end
end
clear cleanupFigure;

rng(rngState);

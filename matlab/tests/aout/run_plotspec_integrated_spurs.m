%% Regression checks for ranking SFDR spurs by integrated lobe power

fprintf('[%s] SFDR integrated spur ranking checks\n', mfilename);

%% A Hann window splits a half-bin spur between two bins. A stronger
% half-bin spur must win even when a weaker coherent spur has the taller bin.
N = 8192;
n = 0:N-1;
cases = [ ...
    1000, 1700.5, 8e-4, 9e-4; ... % half-bin spur stronger (upstream issue 110)
    1700, 1000.5, 8e-4, 9e-4; ... % same spurs, frequency order swapped
    1000, 1700.5, 9e-4, 8e-4; ... % coherent spur stronger
    1700, 1000.5, 9e-4, 8e-4  ... % coherent spur stronger, order swapped
];

for ii = 1:size(cases, 1)
    coherentBin = cases(ii, 1);
    halfBin = cases(ii, 2);
    coherentAmp = cases(ii, 3);
    halfBinAmp = cases(ii, 4);
    signal = 0.8 * sin(2*pi*123*n/N) ...
        + coherentAmp * sin(2*pi*coherentBin*n/N + 0.1) ...
        + halfBinAmp * sin(2*pi*halfBin*n/N + 0.7);

    [~, ~, sfdr] = plotspec( ...
        signal, 1, 2, 1, ...
        'window', 'hann', ...
        'sideBin', 3, ...
        'disp', false, ...
        'label', false);

    expected = 20*log10(0.8 / max(coherentAmp, halfBinAmp));
    assert(abs(sfdr - expected) < 0.01, ...
        'SFDR spur ranking failed for spurs at bins %.1f and %.1f: %.6f dBc, expected %.6f dBc', ...
        coherentBin, halfBin, sfdr, expected);
end

%% Ranking must use the compensated lobe of a masked spur, as SFDR does.
% The spur at bin 507 loses one side bin to the fundamental mask; its visible
% lobe is smaller than the full lobe of the weaker spur at bin 305.
N = 1024;
n = 0:N-1;
signal = sin(2*pi*509*n/N) ...
    + 1e-4 * sin(2*pi*507*n/N) ...
    + 0.95e-4 * sin(2*pi*305*n/N);

[~, ~, sfdr] = plotspec( ...
    signal, 100e6, 2, 5, ...
    'window', 'hann', ...
    'sideBin', 1, ...
    'disp', false, ...
    'label', false);

assert(abs(sfdr - 80) < 0.01, ...
    'Spur ranking ignored masked-lobe compensation: %.6f dBc', sfdr);
